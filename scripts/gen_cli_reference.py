"""Generate docs/reference/cli.md from labrador.cli.build_parser().

Rendered by hand (no argparse HelpFormatter) so the output never depends on terminal width.
Regenerate with `uv run python scripts/gen_cli_reference.py`; `--check` exits 1 if the file is stale.
"""
import argparse
import sys
from pathlib import Path

from labrador import cli

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference" / "cli.md"
HEADER = "<!-- Generated by scripts/gen_cli_reference.py from labrador.cli.build_parser(); do not edit by hand. -->"


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ").strip()


def values(a) -> str:
    if a.choices:
        return ", ".join(f"`{c}`" for c in a.choices)
    if a.nargs == 0:
        return "flag"
    name = getattr(a.type, "__name__", "")
    return {"int": "int", "float": "float", "_positive_int": "positive int"}.get(name, "text" if a.type is None else name)


def row(a) -> str:
    name = ", ".join(f"`{o}`" for o in a.option_strings) if a.option_strings else f"`{a.dest}`"
    default = "" if a.default in (None, False, argparse.SUPPRESS) else f"`{a.default}`"
    return f"| {cell(name)} | {cell(values(a))} | {cell(default)} | {cell(a.help or '')} |"


def synopsis(name: str, actions) -> str:
    positionals = " ".join(a.dest for a in actions if not a.option_strings)
    return " ".join(["labrador", name, "[options]", positionals]).strip()


def render() -> str:
    parser = cli.build_parser()
    subs = next(a for a in parser._actions if hasattr(a, "_name_parser_map"))
    helps = {c.dest: c.help for c in subs._choices_actions}
    out = [HEADER, "", "# CLI reference", "", parser.description, "",
           "Settings, environment variables and the index layout: [Configuration](configuration.md).", ""]
    for name, sp in subs.choices.items():
        actions = [a for a in sp._actions if not isinstance(a, argparse._HelpAction)]
        actions.sort(key=lambda a: bool(a.option_strings))   # positionals first, parser order otherwise
        out += [f"## labrador {name}", "", helps[name], "", f"`{synopsis(name, actions)}`", ""]
        out += ["| Argument | Values | Default | Description |", "| --- | --- | --- | --- |"]
        out += [row(a) for a in actions] + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    check = "--check" in sys.argv[1:]
    text = render()
    if check:
        if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
            sys.exit(0)
        sys.exit("docs/reference/cli.md is stale; regenerate it with: uv run python scripts/gen_cli_reference.py")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
